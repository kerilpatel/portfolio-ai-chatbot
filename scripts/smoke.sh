#!/usr/bin/env bash
#
# End-to-end check of the HTTP contract, with no Azure credentials.
#
# Every status code the README documents is asserted here. These cases were
# verified by hand on each change for a month; a script does it in 30 seconds
# and cannot forget one. The upstream call is expected to fail - there are no
# credentials - so the 200 path is out of scope, but every guard in front of
# it is exercised, and those are the intricate part.
#
# Usage: npm run smoke

set -uo pipefail

PORT="${SMOKE_PORT:-3999}"
BASE="http://127.0.0.1:${PORT}"
ORIGIN="http://localhost:5173"
LOG="$(mktemp)"
FAILURES=0
CHECKS=0

cleanup() {
  [[ -n "${SERVER_PID:-}" ]] && kill "$SERVER_PID" 2>/dev/null
  wait "${SERVER_PID:-}" 2>/dev/null
  rm -f "$LOG"
  rm -rf "${FIXTURES:-}"
}
trap cleanup EXIT

# A distinct client per case, so one case cannot consume another's allowance.
client() { echo "198.51.100.$((RANDOM % 200 + 1))"; }

check() { # check <description> <expected> <actual>
  CHECKS=$((CHECKS + 1))
  if [[ "$2" == "$3" ]]; then
    printf '  ok   %s\n' "$1"
  else
    printf '  FAIL %s — expected %s, got %s\n' "$1" "$2" "$3"
    FAILURES=$((FAILURES + 1))
  fi
}

status() { # status <method> <path> [curl args...]
  local method="$1" path="$2"; shift 2
  curl -s -o /dev/null -w '%{http_code}' -X "$method" "${BASE}${path}" \
    -H "X-Forwarded-For: $(client)" "$@"
}

post_json() { # post_json <body>
  status POST /api/chat -H 'Content-Type: application/json' -d "$1"
}

# Shell-built JSON bit once already: a nested substitution silently sent
# something other than intended, and the check passed for the wrong reason.
# Fixtures are generated by Python and posted from a file instead.
FIXTURES="$(mktemp -d)"
python3 - "$FIXTURES" <<'FIXPY'
import json, pathlib, sys
out = pathlib.Path(sys.argv[1])
(out / "big-body.json").write_text(json.dumps({"message": "a" * 20000}))
(out / "long-message.json").write_text(json.dumps({"message": "a" * 1200}))
(out / "history-61.json").write_text(
    json.dumps({"message": "hi", "history": [{"role": "user", "content": "x"}] * 61})
)
(out / "history-50.json").write_text(
    json.dumps({"message": "hi", "history": [{"role": "user", "content": "x"}] * 50})
)
FIXPY

post_file() { # post_file <fixture name>
  status POST /api/chat -H 'Content-Type: application/json' \
    --data-binary "@${FIXTURES}/$1"
}

if curl -s -o /dev/null --max-time 2 "${BASE}/api/health"; then
  echo "something is already listening on :${PORT}."
  echo "next dev would fall back to another port and every check would hit"
  echo "that other process instead. Stop it, or set SMOKE_PORT."
  exit 1
fi

echo "starting dev server on :${PORT} (no Azure credentials)"
ALLOWED_ORIGIN="$ORIGIN" npx next dev -p "$PORT" > "$LOG" 2>&1 &
SERVER_PID=$!

for _ in $(seq 1 60); do
  curl -s -o /dev/null "${BASE}/api/health" && break
  if ! kill -0 "$SERVER_PID" 2>/dev/null; then
    echo "server exited before becoming ready:"; tail -20 "$LOG"; exit 1
  fi
  sleep 1
done

echo
echo "pages and probes"
check "root page serves"            200 "$(status GET /)"
check "health probe serves"         200 "$(status GET /api/health)"
check "robots.txt serves"           200 "$(status GET /robots.txt)"
check "health reports unconfigured" false \
  "$(curl -s "${BASE}/api/health" | python3 -c 'import json,sys; print(str(json.load(sys.stdin)["configured"]).lower())')"

echo
echo "content type must be json"
check "text/plain refused"          415 "$(status POST /api/chat -H 'Content-Type: text/plain' -d '{"message":"hi"}')"
check "form encoding refused"       415 "$(status POST /api/chat -H 'Content-Type: application/x-www-form-urlencoded' -d 'message=hi')"
check "absent content type refused" 415 "$(status POST /api/chat -d '{"message":"hi"}' -H 'Content-Type:')"
check "charset parameter accepted"  502 "$(status POST /api/chat -H 'Content-Type: application/json; charset=utf-8' -d '{"message":"hi"}')"

echo
echo "request validation"
check "oversized body refused"      413 "$(post_file big-body.json)"
check "malformed json refused"      400 "$(post_json 'not json')"
check "missing message refused"     400 "$(post_json '{}')"
check "blank message refused"       400 "$(post_json '{"message":"   "}')"
check "overlong message refused"    400 "$(post_file long-message.json)"
check "non-array history refused"   400 "$(post_json '{"message":"hi","history":"nope"}')"
check "system role refused"         400 "$(post_json '{"message":"hi","history":[{"role":"system","content":"x"}]}')"
check "history over the cap refused" 400 "$(post_file history-61.json)"
check "history at the cap accepted"   502 "$(post_file history-50.json)"
check "non-boolean stream refused"  400 "$(post_json '{"message":"hi","stream":"yes"}')"

echo
echo "reaches upstream once valid (502 without credentials)"
check "valid request"               502 "$(post_json '{"message":"hi"}')"
check "valid with history"          502 "$(post_json '{"message":"hi","history":[{"role":"user","content":"a"},{"role":"assistant","content":"b"}]}')"
check "valid streaming request"     502 "$(post_json '{"message":"hi","stream":true}')"

echo
echo "cors"
check "preflight from allowed origin"  204 "$(status OPTIONS /api/chat -H "Origin: $ORIGIN")"
check "preflight from other origin"    204 "$(status OPTIONS /api/chat -H 'Origin: https://evil.example')"
ALLOWED=$(curl -s -i -X OPTIONS "${BASE}/api/chat" -H "Origin: $ORIGIN" | grep -ci 'access-control-allow-origin')
REFUSED=$(curl -s -i -X OPTIONS "${BASE}/api/chat" -H 'Origin: https://evil.example' | grep -ci 'access-control-allow-origin')
check "allowed origin gets ACAO"       1 "$ALLOWED"
check "refused origin gets no ACAO"    0 "$REFUSED"

echo
echo "rate limiting"
RL_CLIENT="203.0.113.77"
for _ in $(seq 1 20); do
  curl -s -o /dev/null -X POST "${BASE}/api/chat" -H "X-Forwarded-For: $RL_CLIENT" \
    -H 'Content-Type: application/json' -d '{}' > /dev/null
done
check "21st request limited" 429 "$(curl -s -o /dev/null -w '%{http_code}' -X POST "${BASE}/api/chat" \
  -H "X-Forwarded-For: $RL_CLIENT" -H 'Content-Type: application/json' -d '{}')"
# A spoofed prefix must not buy a fresh allowance.
check "spoofed prefix still limited" 429 "$(curl -s -o /dev/null -w '%{http_code}' -X POST "${BASE}/api/chat" \
  -H "X-Forwarded-For: 1.2.3.4, $RL_CLIENT" -H 'Content-Type: application/json' -d '{}')"
check "retry-after present" 1 "$(curl -s -i -X POST "${BASE}/api/chat" -H "X-Forwarded-For: $RL_CLIENT" \
  -H 'Content-Type: application/json' -d '{}' | grep -ci '^retry-after')"

echo
echo "structured logging"
check "every request logged once" 1 "$(grep -c 'chat_request' "$LOG" > /dev/null && echo 1 || echo 0)"
check "no client ip in the log" 0 "$(grep 'chat_request' "$LOG" | grep -c '203\.0\.113\.77')"

echo
if [[ "$FAILURES" -eq 0 ]]; then
  echo "all ${CHECKS} checks passed"
else
  echo "${FAILURES} of ${CHECKS} checks FAILED"
  echo "--- server log tail ---"; tail -20 "$LOG"
fi
exit "$FAILURES"
